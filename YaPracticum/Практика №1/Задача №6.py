def find_digit(N):
    """
    Рассматриваем бесконечную строку из натуральных чисел:
    1234567891011121314...

    N — это индекс ЦИФРЫ в этой строке (нумерация с 1).
    Наша задача — понять:
    1) в каком разряде находится эта цифра,
    2) в каком именно числе этого разряда,
    3) какой у неё индекс внутри числа.
    """

    # l — длина чисел текущего разряда (1, 2, 3, ...)
    # c — количество чисел в этом разряде (9, 90, 900, ...)
    # start — первое число разряда (1, 10, 100, ...)
    length = 1
    count = 9
    start = 1

    """
    Разбиение строки по разрядам выглядит так:

    1..9        → 9  чисел по 1 цифре → длина подстроки = 1 * 9
    10..99      → 90 чисел по 2 цифры → длина подстроки = 2 * 90
    100..999    → 900 чисел по 3 цифры → длина подстроки = 3 * 900
    ...

    Пока N больше длины текущего разряда,
    значит искомая цифра лежит дальше.
    Мы "отбрасываем" этот разряд и уменьшаем N.
    """

    while N > length * count:
        N -= length * count      # вычитаем длину разряда
        length += 1              # увеличиваем длину чисел
        count *= 10              # чисел в разряде становится в 10 раз больше
        start *= 10              # переходим к следующему разряду (1 → 10 → 100)

    """
    После цикла:
    - мы точно знаем, что искомая цифра находится в текущем разряде
    - N теперь — индекс внутри этого разряда

    Так как каждое число состоит из length цифр,
    то каждые length позиций соответствуют одному числу.
    """

    # A = номер числа в разряде (с нуля)
    A = (N - 1) // length

    # Само число, в котором лежит искомая цифра
    number = start + A

    """
    Несколько соседних N указывают на одно и то же число,
    но на разные цифры внутри него.

    Индекс цифры внутри числа ограничен length
    и находится по формуле:
    """

    digit_index = (N - 1) % length

    # Возвращаем соответствующую цифру
    return int(str(number)[digit_index])


print(find_digit(int(input())))
